"""야간모드 (dark theme) overrides, generated from the day stylesheets.

usage: python scripts/gen-night.py   → writes src/styles/night.generated.css

Every rule of components.css / screens.css / base.css that paints a light background, a light border or
dark text gets an `html.night …` twin with the dark value:
  background var(--c-white) → var(--n-card) · var(--c-slate) → var(--n-slate-bg) · var(--c-on-surface) → var(--n-ink)
  light literal backgrounds → a dark tint of the same hue (neutral ones → var(--n-card-2))
  light literal borders / outlines → var(--n-line) · dark literal text → var(--n-text)
Tokens (--c-text, --c-surface …) and the hand-tuned parts (screen backgrounds, gradient text …) are in night.css.
Run it again whenever the day stylesheets change.
"""
import colorsys
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'styles'
SOURCES = ['base.css', 'components.css', 'screens.css']
OUT = ROOT / 'night.generated.css'

HEX = re.compile(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b')


def rgb(h):
    h = h.lstrip('#')
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def lum(c):
    r, g, b = c
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def dark_tint(c):
    """A light background colour → its night counterpart: same hue, dark."""
    h, l, s = colorsys.rgb_to_hls(*c)
    if s < 0.18:
        return 'var(--n-card-2)'
    r, g, b = colorsys.hls_to_rgb(h, 0.17, min(s, 0.5))
    return '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))


def rules(css):
    """Top-level (selector, body) pairs; @keyframes / @font-face blocks are skipped, @media is flattened."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            return
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith('@media'):
            yield from rules(body)
        elif not head.startswith('@'):
            yield head, body
        i = k


def night_selector(sel):
    sel = sel.strip()
    if sel.startswith(':root') or not sel:
        return None
    m = re.match(r'html((?:[.#:\[][^\s]*)?)(\s.*)?$', sel)
    if m:  # html.desktop #stage → html.night.desktop #stage
        return f'html.night{m.group(1) or ""}{m.group(2) or ""}'
    return f'html.night {sel}'


def convert(prop, value):
    p, v = prop.strip(), value.strip()
    if p in ('background', 'background-color'):
        if v == 'var(--c-white)':
            return 'var(--n-card)'
        if v == 'var(--c-slate)':
            return 'var(--n-slate-bg)'
        if v == 'var(--c-on-surface)':
            return 'var(--n-ink)'
        m = HEX.fullmatch(v)
        if m and lum(rgb(v)) > 0.78:
            return dark_tint(rgb(v))
        m = re.fullmatch(r'rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\s*\)', v)
        if m:
            return f'rgba(35, 43, 56, {m.group(1)})'
        return None
    if p in ('border', 'border-top', 'border-bottom', 'border-left', 'border-right', 'border-color', 'outline'):
        changed = False

        def sub(m):
            nonlocal changed
            c = rgb(m.group(0))
            h, l, s = colorsys.rgb_to_hls(*c)
            if lum(c) > 0.7 and s < 0.45:
                changed = True
                return 'var(--n-line)'
            return m.group(0)

        out = HEX.sub(sub, v)
        return out if changed else None
    if p == 'color':
        m = HEX.fullmatch(v)
        if m and lum(rgb(v)) < 0.3:
            return 'var(--n-text)'
    return None


def main():
    out = ['/* GENERATED by scripts/gen-night.py — do not edit; hand-tuned night styles live in night.css */']
    count = 0
    for name in SOURCES:
        css = (ROOT / name).read_text(encoding='utf-8')
        for head, body in rules(css):
            decls = []
            for d in body.split(';'):
                if ':' not in d:
                    continue
                prop, value = d.split(':', 1)
                important = '!important' in value
                new = convert(prop, value.replace('!important', ''))
                if new:
                    decls.append(f'  {prop.strip()}: {new}{" !important" if important else ""};')
            if not decls:
                continue
            sels = [night_selector(s) for s in head.split(',')]
            sels = [s for s in sels if s]
            if not sels:
                continue
            out.append(f'/* {name} */\n' + ',\n'.join(sels) + ' {\n' + '\n'.join(decls) + '\n}')
            count += 1
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{OUT.name}: {count} rules')


main()
